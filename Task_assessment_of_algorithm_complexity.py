"""
    1. Алгоритм проверки наличия дубликатов в массиве.

    Алгоритм использует два вложенных цикла:
        ¤ Внешний цикл проходит по всем элементам массива (n итераций).
        ¤ Внутренний цикл начинается со следующего элемента после внешнего и идёт до конца массива.

    Количество сравнений для каждого шага внешнего цикла уменьшается линейно: (n - 1) для первой итерации, (n - 2) для
второй итерации и так далее, пока не дойдёт до нуля.

    Суммарное количество сравнений можно представить следующим образом:

        (n - 1) + (n - 2) + ... + 1 = n(n - 1)/2 – Что упрощается до n ^ 2

    Таким образом, данный алгоритм имеет квадратичную временную сложность О(n ^ 2).
"""


def has_duplicates(arr):
    for i in range(len(arr)):
        for j in range(i + 1, len(arr)):
            if arr[i] == arr[j]:
                return True
    return False


"""
    2. Алгоритм поиска максимального элемента в неотсортированном массиве.

    Для поиска максимального элемента в неотсортированном массиве необходимо проверить все элементы, так как любой 
непроверенный элемент потенциально может быть максимальным. Таким образом, данный алгоритм имеет линейную временную 
сложность О(n).
"""


def find_max(arr):
    max_val = arr[0]
    for val in arr:
        if val > max_val:
            max_val = val
    return max_val


"""
    3. Алгоритм сортировки выбором (Selection Sort).

    Сортировка выбором - это алгоритм сортировки, который на каждом шаге выбирает минимальный элемент из оставшихся и 
ставит его на правильное место. Временная сложность сортировки выбором - O(n^2) (квадратичная) в лучшем, среднем и 
худшем случаях.
"""


def selection_sort(arr):
    for i in range(len(arr)):
        min_idx = i
        for j in range(i + 1, len(arr)):
            if arr[j] < arr[min_idx]:
                min_idx = j
        arr[i], arr[min_idx] = arr[min_idx], arr[i]


"""
    4. Алгоритм быстрой сортировки (Quick Sort).

     В среднем случае быстрая сортировка имеет временную сложность O(n log n). Этот алгоритм разделяет массив на 
подмассивы, сортирует их и затем объединяет весь массив. В среднем время разделения и объединения составляет O(log n),
а каждый подмассив сортируется за O(n). В худшем случае быстрая сортировка может иметь квадратичную временную сложность,
если опорный элемент каждый раз выбирается как самый большой или самый маленький элемент. Это случается, например, если
массив уже отсортирован в обратном порядке.
"""


def quick_sort(arr):
    if len(arr) <= 1:
        return arr
    pivot = arr[len(arr) // 2]
    left = [x for x in arr if x < pivot]
    middle = [x for x in arr if x == pivot]
    right = [x for x in arr if x > pivot]
    return quick_sort(left) + middle + quick_sort(right)


"""
    5. Алгоритмы вычисления n-го числа Фибоначчи (рекурсивно).

    Алгоритм вычисления n-го числа Фибоначчи рекурсивным способом  имеет экспоненциальную временную сложность О(2 ^ n).

    Рекурсивный алгоритм Фибоначчи создаёт бинарное дерево рекурсивных вызовов:

        ¤ Для вычисления F(n) нужно вычислить F(n - 1) и F(n - 2).
        ¤ Каждый из этих вызовов, в свою очередь, делает ещё два вызова.
        ¤ Это приводит к экспоненциальному росту количества вызовов.
"""


def fibonacci_recursive(n):
    if n <= 1:
        return n
    return fibonacci_recursive(n - 1) + fibonacci_recursive(n - 2)
